#!/usr/bin/env python3
"""Inventory wired Rust datastore routes against Play's latest datastore routes.

Measures registrations only, not behavioral parity or cutover readiness. Version
aliases, automatic HEAD, the front page, and legacy overrides are not counted.
"""
import argparse
from collections import Counter
from pathlib import Path
import re
import sys

from route_inventory import normalized as normalized_param, route_calls


def normalized(path):
    """Also treat Play's `*name` wildcard like Axum's `{*name}` capture."""
    return normalized_param(re.sub(r"/\*[A-Za-z][A-Za-z0-9_]*$", "/:param", path))

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "datastore"
OUTPUT = PACKAGE / "MIGRATION_STATUS.md"

# Axum captures whole path segments. The handler checks these Play literal
# prefixes explicitly; binary_data_routes.rs exercises the actual Knossos URL.
PREFIX_BINDERS = {
    "/datasets/{datasetId}/layers/{dataLayerName}/{mag}/{x}/{y}/{z}/bucket.raw":
    "/datasets/:datasetId/layers/:dataLayerName/mag:mag/x:x/y:y/z:z/bucket.raw",
}


def render():
    lib = (PACKAGE / "src/lib.rs").read_text()
    modules = {"lib"} | set(re.findall(r"\b([\w:]+)::router\(", lib))
    rust = {}
    for module in sorted(modules):
        file = f"src/{module.replace('::', '/')}.rs"
        for call in route_calls((PACKAGE / file).read_text()):
            path = re.match(r'\s*"([^"\\]+)"\s*,', call)
            if not path:
                raise ValueError(f"Nonliteral route in {file}")
            path = path[1]
            if not path.startswith("/data/"):
                continue
            path = path.removeprefix("/data")
            path = PREFIX_BINDERS.get(path, path)
            for method in re.findall(r"\b(get|post|put|patch|delete|head|options)\s*\(", call):
                key = (method.upper(), normalized(path))
                if key in rust:
                    raise ValueError(f"Duplicate Rust route: {key}")
                rust[key] = file
    rows = []
    legacy_file = ROOT.parent / "webknossos-datastore/conf/datastore.latest.routes"
    for line in legacy_file.read_text().splitlines():
        match = re.match(r"^(GET|POST|PUT|PATCH|DELETE|HEAD|OPTIONS)\s+(\S+)\s+@.*\.controllers\.(\w+)\.", line)
        if match:
            method, path, controller = match.groups()
            rows.append((method, path, controller, rust.get((method, normalized(path)))))
    missing = Counter(row[2] for row in rows if not row[3])
    implemented = sum(bool(row[3]) for row in rows)
    lines = ["# Datastore migration status", "",
        "Generated by `python3 ../tools/datastore_route_inventory.py` from wired Rust routers and `webknossos-datastore/conf/datastore.latest.routes`.", "",
        f"**{implemented} of {len(rows)} latest datastore method/path registrations implemented.** Registration coverage does not prove behavioral parity or migration completion.", "",
        "Paths are served under `/data` and the existing `/data/v10` through `/data/v16` aliases. Legacy overrides require separate implementations. Knossos captures whole segments in Axum and validates Play's literal prefixes in the handler.", "",
        "Evidence: README.md and ../checkpoints/datastore-ds2-*.md, datastore-ds3-data-access.md, datastore-ds4-binary-data.md, datastore-ds4-datasource.md, datastore-ds4-inbox.md, datastore-ds4-proxy-finddata-zarr.md, datastore-ds5-agglomerates.md, datastore-ds5-hdf5-agglomerates.md, datastore-ds5-segment-index.md, datastore-ds5-segment-statistics.md, datastore-ds5-mesh-files.md, datastore-ds5-draco-full-mesh.md, datastore-ds5-connectomes.md; plan and batch queue in ../checkpoints/datastore-plan.md. Segment-index/agglomerate and mesh-file metadata/chunk routes support their HDF5/Zarr3/precomputed variants; statistics read Zarr3 metric tables and actual index-based binary buckets. Full/ad-hoc meshes, typed JSON/agglomerate mappings, Draco→STL and statistics-file/mesh surface areas are wired. Connectomes support HDF5/Zarr3 CSR/CSC synapses, positions, partners and legends with actual Scala oracles. Still missing: Compresso codec and managed-S3 upload targets; legacy/differential/performance and cutover work remains DS6.", "",
        "## Remaining routes by controller", "", "| Controller | Remaining |", "| --- | ---: |"]
    lines.extend(f"| {controller} | {count} |" for controller, count in sorted(missing.items()))
    lines += ["", "## Latest route inventory", "", "| Method | Path under `/data` | Implementation |", "| --- | --- | --- |"]
    for method, path, _, file in rows:
        implementation = f"[{file}]({file})" if file else "Pending"
        lines.append(f"| {method} | `{path}` | {implementation} |")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            print("Datastore inventory is stale; run python3 tools/datastore_route_inventory.py", file=sys.stderr)
            return 1
    else:
        OUTPUT.write_text(content)
        print(f"Updated {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
