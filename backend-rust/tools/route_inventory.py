#!/usr/bin/env python3
"""Inventory explicitly registered Rust routes against Play's latest application API.

This measures implemented route registrations, not behavioral parity or backend
feature completeness. Version aliases and automatic HEAD routes are not counted.
"""
import argparse
from collections import Counter
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "MIGRATION_STATUS.md"


def route_calls(source):
    for match in re.finditer(r"\.route\(", source):
        start = match.end()
        depth = 1
        quoted = escaped = False
        for index in range(start, len(source)):
            char = source[index]
            if quoted:
                if escaped:
                    escaped = False
                elif char == "\\":
                    escaped = True
                elif char == '"':
                    quoted = False
                continue
            if char == '"':
                quoted = True
            elif char == "(":
                depth += 1
            elif char == ")":
                depth -= 1
                if depth == 0:
                    yield source[start:index]
                    break
        else:
            raise ValueError("Unterminated Rust route call")


def normalized(path):
    path = re.sub(r"\{[^}]+\}", ":param", path)
    return re.sub(r":[A-Za-z][A-Za-z0-9_]*", ":param", path)


def render():
    lib = (ROOT / "src/lib.rs").read_text()
    modules = {"lib"} | set(re.findall(r"\b(\w+)::(?:\w+_)?router\(", lib))
    # Legacy dataset adapters implement older wire contracts for the same paths.
    # Count each latest API registration once, including split list/read routers.
    modules.discard("legacy_datasets")
    rust = {}
    for module in sorted(modules):
        for call in route_calls((ROOT / f"src/{module}.rs").read_text()):
            path = re.match(r'\s*"([^"\\]+)"\s*,', call)
            if not path:
                raise ValueError(f"Nonliteral route in {module}")
            methods = re.findall(r"\b(get|post|put|patch|delete|head|options)\s*\(", call[path.end():])
            for method in methods:
                key = (method.upper(), normalized(path[1]))
                if key in rust:
                    raise ValueError(f"Duplicate Rust route: {key}")
                rust[key] = f"src/{module}.rs"
    legacy = []
    for line in (ROOT.parent / "conf/webknossos.latest.routes").read_text().splitlines():
        match = re.match(r"^(GET|POST|PUT|PATCH|DELETE|HEAD|OPTIONS)\s+(\S+)\s+controllers\.(\w+)\.", line)
        if match:
            method, path, controller = match.groups()
            legacy.append((method, path, controller, rust.get((method, normalized(path)))))
    implemented = sum(bool(row[3]) for row in legacy)
    lines = ["# Application migration status", "", 
        "Generated by `python3 tools/route_inventory.py` from registered Rust routes and Play's latest routes.", "",
        f"**{implemented} of {len(legacy)} application method/path registrations implemented.** This is route coverage, not a claim of behavioral parity or complete backend migration.", "",
        "Implemented resources are available under `/api` and `/api/v10` through `/api/v16`. Dataset list defaults and safe segment-ID serialization preserve the older version contracts. `/health/live` and `/health/ready` are Rust operational endpoints. The datastore and tracingstore are separate services and are not included in this count.", "",
        "Datastore service progress (separate `datastore/` package, Play `webknossos-datastore/conf/datastore.latest.routes`) is tracked in [datastore/MIGRATION_STATUS.md](datastore/MIGRATION_STATUS.md), generated by `python3 tools/datastore_route_inventory.py`; its plan and batch queue live in checkpoints/datastore-plan.md.", "",
        "## Remaining work in dependency order", "",
        "1. Complete annotation lifecycle/IO and task creation/allocation with tracingstore integration; job and AI submission routes are registered.",
        "2. Complete main-application datastore/tracingstore callbacks and OIDC/WebAuthn authentication ceremonies. The table below is the current route-level source of truth.",
        "3. Implement real mail delivery, remaining external side effects and background workers. Registered routes can still have documented behavioral gaps; review checkpoints and README before routing traffic.",
        "4. Differential tests against Play, observability/performance checks, schema migration ownership and staged traffic cutover.",
        "5. Datastore, then tracingstore engines: storage formats, native codecs, streaming/protobuf, FossilDB, update semantics, concurrency and binary compatibility.", "",
        "## Remaining routes by controller", "", "| Controller | Remaining |", "| --- | ---: |"]
    pending = Counter(row[2] for row in legacy if not row[3])
    lines.extend(f"| {controller} | {count} |" for controller, count in sorted(pending.items()))
    lines += ["", "## Full application inventory", "", "| Method | Path under `/api` | Implementation |", "| --- | --- | --- |"]
    for method, path, _, implementation in legacy:
        target = f"[{implementation}]({implementation})" if implementation else "Pending"
        lines.append(f"| {method} | `{path}` | {target} |")
    lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    content = render()
    if arguments.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            print("Migration inventory is stale; run python3 tools/route_inventory.py", file=sys.stderr)
            return 1
    else:
        OUTPUT.write_text(content)
        print(f"Updated {OUTPUT.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
